"""Rasterises the glyphs the Today page uses into src/render/font.ts.

The page is drawn on the device in plain JavaScript (no canvas there), so it
needs ready-made glyph bitmaps. Inter is licensed under the SIL OFL 1.1.

    python3 tools/make_font.py
"""

import base64
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src/render/font.ts"
FONT_DIR = Path("/usr/share/fonts/opentype/inter")

FACES = {
    "r24": ("Inter-Regular.otf", 24),
    "r30": ("Inter-Regular.otf", 30),
    "b20": ("Inter-SemiBold.otf", 20),
    "b44": ("Inter-Bold.otf", 44),
}

CODES = (
    list(range(32, 127))
    + list(range(160, 256))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026, 0x2022, 0x2192, 0x21BB, 0x2713, 0x00B7, 0x20AC]
)


def pack4(pixels):
    """Alpha 0..255 → 4 bits, two pixels per byte."""
    out = bytearray()
    for i in range(0, len(pixels), 2):
        a = pixels[i] >> 4
        b = (pixels[i + 1] >> 4) if i + 1 < len(pixels) else 0
        out.append((a << 4) | b)
    return bytes(out)


def build(font_file, size):
    font = ImageFont.truetype(str(FONT_DIR / font_file), size)
    ascent, descent = font.getmetrics()
    glyphs = {}
    blob = bytearray()
    for code in CODES:
        ch = chr(code)
        advance = round(font.getlength(ch))
        canvas = Image.new("L", (size * 3, size * 3), 0)
        d = ImageDraw.Draw(canvas)
        origin_x, baseline = size, size * 2
        d.text((origin_x, baseline), ch, font=font, fill=255, anchor="ls")
        box = canvas.getbbox()
        if not box:
            glyphs[code] = [0, 0, 0, 0, advance, 0]
            continue
        glyph = canvas.crop(box)
        w, h = glyph.size
        offset = len(blob)
        blob += pack4(list(glyph.getdata()))
        # left bearing, rows above the baseline
        glyphs[code] = [w, h, box[0] - origin_x, baseline - box[1], advance, offset]
    return {"size": size, "ascent": ascent, "descent": descent, "glyphs": glyphs}, bytes(blob)


def main():
    faces = {}
    blobs = {}
    for name, (file, size) in FACES.items():
        faces[name], blobs[name] = build(file, size)
    lines = [
        "/* eslint-disable quotes */",
        "/* Generated by tools/make_font.py from Inter (SIL OFL 1.1). Do not edit. */",
        "export interface FaceData {",
        "  size: number;",
        "  ascent: number;",
        "  descent: number;",
        "  /** char code → [width, height, left bearing, rows above baseline, advance, data offset] */",
        "  glyphs: Record<number, [number, number, number, number, number, number]>;",
        "  /** 4-bit alpha, two pixels per byte, glyph after glyph; base64 */",
        "  data: string;",
        "}",
        "",
        "export const FACES: Record<string, FaceData> = {",
    ]
    for name in FACES:
        face = dict(faces[name])
        face["data"] = base64.b64encode(blobs[name]).decode()
        lines.append(f"  {name}: {json.dumps(face, separators=(',', ':'))},")
    lines.append("};")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
